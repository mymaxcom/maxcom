// Writes the generated COUNTRIES part of packages/core/src/prayer/countries.ts from the IANA tz database
// (zone.tab = one row per country zone, iso3166.tab = every country code). Run once, commit the output.
// Usage: node scripts/fetch-country-zones.mjs [--zone zone.tab --iso iso3166.tab]   (files instead of https)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'packages', 'core', 'src', 'prayer', 'countries.ts');
const MARKER = '// ---- HAND-KEPT BELOW: the script preserves everything from this line on ----';
const BASE = 'https://data.iana.org/time-zones/tzdb/';

const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : null; };

async function load(name, file) {
  if (file) return readFileSync(file, 'utf8');
  const res = await fetch(BASE + name, { redirect: 'error', signal: AbortSignal.timeout(30000) });
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  return await res.text();
}

const rows = (text) => text.split(/\r?\n/).filter((l) => l !== '' && !l.startsWith('#')).map((l) => l.split('\t'));

const zoneTab = await load('zone.tab', arg('--zone'));
const isoTab = await load('iso3166.tab', arg('--iso'));

const zones = new Map();
for (const [cc, , tz] of rows(zoneTab)) {
  if (!/^[A-Z]{2}$/.test(cc) || !tz) continue;
  if (!zones.has(cc)) zones.set(cc, []);
  zones.get(cc).push(tz);
}
const codes = rows(isoTab).map((r) => r[0]).filter((c) => /^[A-Z]{2}$/.test(c)).sort();
if (codes.length < 200 || !zones.has('MY') || !zones.has('KE')) throw new Error('unexpected tz data; refusing to write');

const lines = codes.map((c) => `  { code: '${c}', timezones: [${(zones.get(c) ?? ['UTC']).map((z) => `'${z}'`).join(', ')}] },`);
const generated = `// GENERATED by scripts/fetch-country-zones.mjs from the IANA tz database (zone.tab, iso3166.tab). Do not edit by hand.
export const COUNTRIES: ReadonlyArray<{ code: string; timezones: readonly string[] }> = [
${lines.join('\n')}
];
`;

let hand = '';
try {
  const old = readFileSync(target, 'utf8');
  const at = old.indexOf(MARKER);
  if (at >= 0) hand = old.slice(at);
} catch { /* first run */ }
if (hand === '') throw new Error(`${target} must hold the hand-kept part below the marker line first`);
writeFileSync(target, `${generated}\n${hand}`);
console.log(`wrote ${codes.length} countries to ${target}`);
