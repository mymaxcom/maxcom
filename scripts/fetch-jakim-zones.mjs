// Writes packages/core/src/prayer/jakimZones.ts from the e-Solat zone page. Run once, commit the output
// and the saved page (packages/core/test/fixtures/esolat-zones-<date>.html).
// Usage: node scripts/fetch-jakim-zones.mjs [--file saved-page.html]   (a saved page instead of https)
// Centre coordinates come from scripts/jakim-zone-centres.json; a zone without one is written without
// coordinates and reported.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseZoneOptions } from '../packages/core/src/prayer/zoneOptions.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = 'https://www.e-solat.gov.my/index.php?siteId=24&pageId=24';
const MAX_BYTES = 2 * 1024 * 1024;
const STATES = {
  JHR: 'Johor', KDH: 'Kedah', KTN: 'Kelantan', MLK: 'Melaka', NGS: 'Negeri Sembilan', PHG: 'Pahang',
  PLS: 'Perlis', PNG: 'Pulau Pinang', PRK: 'Perak', SBH: 'Sabah', SGR: 'Selangor', SWK: 'Sarawak',
  TRG: 'Terengganu', WLY: 'Wilayah Persekutuan',
};

const fileArg = process.argv.indexOf('--file');
let html;
if (fileArg > 0) {
  html = readFileSync(process.argv[fileArg + 1], 'utf8');
} else {
  const res = await fetch(PAGE, { redirect: 'error', signal: AbortSignal.timeout(30000), headers: { 'user-agent': 'MAXCOM/build-script' } });
  if (!res.ok) throw new Error(`e-Solat page: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length > MAX_BYTES) throw new Error('e-Solat page is over 2 MB; refusing');
  html = buf.toString('utf8');
}

const zones = parseZoneOptions(html);
if (zones.length < 40 || !zones.some((z) => z.code === 'SGR01')) {
  throw new Error(`only ${zones.length} zones (or no SGR01) in the page; refusing to write`);
}
const centres = JSON.parse(readFileSync(join(root, 'scripts', 'jakim-zone-centres.json'), 'utf8'));
const missing = [];
const rows = zones.map((z) => {
  const state = STATES[z.code.slice(0, 3)];
  if (!state) throw new Error(`no state for zone ${z.code}`);
  const c = centres[z.code];
  if (!c) missing.push(z.code);
  return `  { code: '${z.code}', state: '${state}', name: ${JSON.stringify(z.name)}, lat: ${c ? c[0] : 'null'}, lon: ${c ? c[1] : 'null'} },`;
});
const day = new Date().toISOString().slice(0, 10);
const out = `// GENERATED by scripts/fetch-jakim-zones.mjs from the e-Solat zone page (${PAGE}). Do not edit by hand.
// lat/lon are hand-kept district centres (scripts/jakim-zone-centres.json), used to suggest a zone from a location.
export const JAKIM_ZONES_FETCHED_AT = '${day}';

export const JAKIM_STATES: Readonly<Record<string, string>> = ${JSON.stringify(STATES, null, 2)};

export const JAKIM_ZONES: ReadonlyArray<{ code: string; state: string; name: string; lat: number | null; lon: number | null }> = [
${rows.join('\n')}
];
`;
writeFileSync(join(root, 'packages', 'core', 'src', 'prayer', 'jakimZones.ts'), out);
if (fileArg < 0) {
  writeFileSync(join(root, 'packages', 'core', 'test', 'fixtures', `esolat-zones-${day}.html`), html);
} else {
  copyFileSync(process.argv[fileArg + 1], join(root, 'packages', 'core', 'test', 'fixtures', `esolat-zones-${day}.html`));
}
console.log(`wrote ${zones.length} zones${missing.length ? `; NO CENTRE for ${missing.join(', ')}` : ''}`);
